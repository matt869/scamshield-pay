const dictionaries: Record<Language, Copy> = { en, es, fil };

export function t(language: Language): Copy {
  return dictionaries[language];
}

export function languageFromHeader(acceptLanguage: string | null): Language {
  const first = acceptLanguage?.split(",")[0]?.trim().toLowerCase() ?? "";
  if (first.startsWith("es")) return "es";
  // Browsers report Filipino as "fil", and some older ones as "tl" (Tagalog).
  if (first.startsWith("fil") || first.startsWith("tl")) return "fil";
  return "en";
}
